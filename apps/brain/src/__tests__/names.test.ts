// The three parts are the App, the Server and Go. No file in apps/ or packages/ names one as "go" joined to "server",
// "app" or "brain" with a hyphen; the only such name allowed is the repo's own, vestra-ai/go-brain.
import { readdirSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

/** The repo root, from apps/brain/src/__tests__/. */
const ROOT = new URL('../../../../', import.meta.url);

/** Built from its parts, so this file never matches itself. */
const WRONG_NAME = new RegExp(`\\bgo-(${['server', 'app', 'brain'].join('|')})\\b`, 'gi');
const REPO = 'vestra-ai/';

/** Installed, built or generated by a tool run, never written by us. */
const SKIP_DIRS = new Set(['node_modules', 'dist', 'out', 'coverage', '.turbo', '__pycache__', '.pytest_cache']);
const BINARY = /\.(png|jpe?g|gif|webp|ico|svg|woff2?|ttf|otf|mp3|wav|mp4|pdf|zip|gz|pyc)$/i;

function filesUnder(dir: URL): URL[] {
  const out: URL[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name) && !e.name.endsWith('.egg-info')) out.push(...filesUnder(new URL(`${e.name}/`, dir)));
    } else if (e.isFile() && !BINARY.test(e.name)) {
      out.push(new URL(e.name, dir));
    }
  }
  return out;
}

/** Each wrong name in a text, by line; the repo's own name is not one. */
function wrongNames(text: string): Array<{ line: number; name: string }> {
  const found: Array<{ line: number; name: string }> = [];
  for (const m of text.matchAll(WRONG_NAME)) {
    const at = m.index ?? 0;
    if (text.slice(Math.max(0, at - REPO.length), at) === REPO) continue;
    found.push({ line: text.slice(0, at).split('\n').length, name: m[0] });
  }
  return found;
}

describe('the parts are named App, Server and Go', () => {
  it('finds a hyphenated name, and lets the repo name through', () => {
    const wrong = ['go', 'server'].join('-');
    const shouted = ['GO', 'App'].join('-');
    const text = ['clone vestra-ai/go-brain', `a ${wrong} call`, `the ${shouted}`].join('\n');
    expect(wrongNames(text)).toEqual([{ line: 2, name: wrong }, { line: 3, name: shouted }]);
  });

  it('no file in apps/ or packages/ uses one', () => {
    const files = [...filesUnder(new URL('apps/', ROOT)), ...filesUnder(new URL('packages/', ROOT))];
    expect(files.length).toBeGreaterThan(100);
    const found = files.flatMap((f) =>
      wrongNames(readFileSync(f, 'utf8')).map((w) => `${f.pathname.slice(ROOT.pathname.length)}:${w.line} ${w.name}`),
    );
    expect(found).toEqual([]);
  });
});
