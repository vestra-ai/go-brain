/**
 * Icon hint for tool display - frontend resolves to actual icon/emoji
 * Categories rather than specific icons to allow flexibility
 */
export type ToolIconHint =
  | 'search'     // WebSearch, Grep, Glob
  | 'web'        // WebFetch, URL operations
  | 'file'       // Read, file operations
  | 'file-edit'  // Write, Edit
  | 'terminal'   // Bash commands
  | 'package'    // Package installation (npm, pip)
  | 'git'        // Git operations
  | 'agent'      // Task, subagent spawning
  | 'api'        // API calls, MCP tools
  | 'database'   // Database operations
  | 'success'    // Completed successfully
  | 'error'      // Failed
  | 'default';   // Fallback

/**
 * Human-readable summary for tool operations
 * Generated by agent, displayed by frontend
 */
export interface ToolSummary {
  /** Action being performed: "Searching", "Reading", "Installing" */
  action: string;
  /** Target of the action: filename, query, package name */
  target: string;
  /** Optional additional context */
  details?: string;
  /** Icon category hint - frontend resolves to actual icon */
  iconHint?: ToolIconHint;
}

