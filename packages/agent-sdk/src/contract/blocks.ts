/**
 * Turn footer block — injected by server at persistence time.
 * Stores the completion/interrupted summary so it survives page reloads.
 */
export interface TurnFooterBlock {
  type: 'turn_footer';
  durationMs: number;
  interrupted: boolean;
  /**
   * Why the turn was interrupted, when `interrupted` is true.
   * - undefined / 'user' → the user pressed Stop ("[Interrupted by the user]").
   * - 'disconnected' → the sandbox connection dropped (standby / deploy /
   *   upgrade) and the server reconciled the task. NOT a user action — the UI
   *   must not blame the user; the real result may still arrive on reconnect.
   * - 'credits_exhausted' → the account ran out of credits and the runner
   *   stopped every live task. Also not a user action: the credit kill takes
   *   the same code path a Stop does, so without this the whole stack down to
   *   the trace store called it the person's Stop.
   * - 'lead' → the lead agent stopped one of its own background helpers
   *   (`StopHelper`). Not a user action either, and the person must not read
   *   "you stopped this" for a call the lead made on their behalf.
   * - 'restart' → a graceful shutdown paused the turn at a settled point and the
   *   next runner continues it (PLANNED_RESTART_RESUME_V1): a pause for an update.
   *
   * WRITTEN ONLY WHEN IT IS NOT 'user'. A stop by the person leaves the key
   * absent, exactly as it was before the reason existed, so that footer is
   * byte-identical on the wire and every pin on it still holds.
   */
  interruptReason?: 'user' | 'disconnected' | 'credits_exhausted' | 'lead' | 'restart';
  word?: string;
  stopReason?: string;
  /**
   * Phase 5: credits consumed this turn, derived from SDK's total_cost_usd.
   * Populated post-hoc on AGENT_RESULT (fires after MESSAGE_COMPLETE persists),
   * so there's a ~1s window where this is undefined on the latest turn.
   */
  creditCost?: number;
  /**
   * K6 P4: structured terminal reason for the turn, mapped from the
   * TurnOutcome via terminalReasonFor(). Populated post-hoc by the relay
   * ONLY for arms with capabilities.surfacesTerminalReason (native/openai);
   * the Claude SDK arm is byte-identical and never sets this. Absent === treat
   * as a clean completion.
   */
  terminalReason?: TerminalReasonView;
  /**
   * Several accounts per engine: 'switched' = the turn ended rate_limited on the person's own plan
   * and the next account carried the task on. Its terminalReason still says what happened; this
   * says it was handled, so the footer shows no failure. Written by the server at the turn end.
   */
  planLimit?: 'switched';
  /**
   * With planLimit: the exact resume_at (ISO) the switch's safety net armed. The web ignores the
   * task's resumeAt only while it is this instant; any other resumeAt is a real pause.
   */
  planLimitNetAt?: string;
}

