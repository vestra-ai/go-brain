/**
 * Tool use content block - shows tool being invoked
 */
export interface ToolUseBlock {
  type: 'tool_use';
  toolUseId: string;
  toolName: string;
  toolInput: unknown;
  status: ToolStatus;
  result?: unknown;
  isError?: boolean;
  startTime: Date;
  endTime?: Date;
  summary?: ToolSummary;
  resultSummary?: ToolSummary;
  subagentOutput?: string;
  subagentType?: string;
  /** Subagent display metadata (set by SUBAGENT_START) */
  subagentName?: string;
  subagentIcon?: string;
  subagentColor?: string;
  /** How the subagent ended, as observed on the parent tool_use block. `paused` —
   *  the child suspended for a human-in-the-loop interaction (it did not fail);
   *  the "needs you" affordance owns the render until the pause resolves.
   *  `stopped` — under the orchestration walls the child came back with a
   *  non-completed reason (stopped, capped, refused, failed): partial work, never
   *  "done". See `subagentStopReason` for which. */
  subagentStatus?: 'running' | 'completed' | 'error' | 'paused' | 'stopped';
  /** Why a `stopped` lane stopped, verbatim from `SUBAGENT_END.stopReason`
   *  (`turn_cap` | `stopped_by_user` | `stopped_by_parent` | `refused` | `failed`).
   *  Absent on every pre-walls row, which is why it is a plain string rather than
   *  the runner's union: the render must survive a reason it has never seen. */
  subagentStopReason?: string;
  /** Accumulated subagent streamed text (from SUBAGENT_TEXT_DELTA) */
  subagentText?: string;
  /** AI-generated summary from task_notification (readable completion summary) */
  subagentSummary?: string;
  /** UI-only flag — true if the user manually toggled expand/collapse.
   *  When true, disables the auto-expand-while-running and auto-collapse-on-complete
   *  behaviors. Lives on the block so it survives virtualized re-mounts of the
   *  message list. Not persisted to the database. */
  userToggled?: boolean;
  /** Structured tool activity log from subagent (from SUBAGENT_TOOL_USE/TOOL_RESULT).
   *  @deprecated Prefer `subagentContent` — kept for legacy data compatibility. */
  subagentTools?: Array<{
    tool: string;
    input?: unknown;
    result?: unknown;
    subToolUseId?: string;
    status: 'running' | 'completed';
    startedAt?: number;
    completedAt?: number;
  }>;
  /** Chronological subagent stream: text + tool_use + tool_result blocks in arrival order.
   *  Populated by SUBAGENT_TEXT_DELTA / SUBAGENT_TOOL_USE / SUBAGENT_TOOL_RESULT handlers.
   *  Rendered with the same ContentBlockRenderer used for the main agent's content, so
   *  subagent tools get their normal mini-pill / bare-row / etc. UI inside a nested rail. */
  subagentContent?: ContentBlock[];
  /** Server-enriched display metadata for Composio/integration tools */
  display?: ToolDisplay;
  /** Server-enriched result display for Composio/integration tools */
  resultDisplay?: ToolResultDisplay;
  permissionPending?: boolean;
  userAnswers?: Record<string, string>;
  /** Real-time progress metrics from SDK task_progress events */
  subagentProgress?: {
    description: string;
    summary?: string;
    totalTokens: number;
    toolUses: number;
    durationMs: number;
    lastToolName?: string;
  };
  /** Accumulated raw input_json_delta chunks (tool input being generated) */
  partialInput?: string;
  /** Elapsed seconds from tool_progress events (live timer during execution) */
  elapsedSeconds?: number;
  /** AI summary from tool_use_summary (replaces default collapsed label) */
  aiSummary?: string;
  /** Live per-line output streamed mid-turn via tool_progress (Monitor tool, K5-T7).
   *  Each AGENT_TOOL_PROGRESS event carrying a `line` appends here as the process
   *  emits it. Live-only (never journaled — the journal keeps only the final
   *  tool_result). Capped client-side to avoid unbounded growth. */
  progressLines?: string[];
}

/**
 * Tool result content block
 */
export interface ToolResultBlock {
  type: 'tool_result';
  toolUseId: string;
  content: unknown;
  isError?: boolean;
  /**
   * TELEMETRY PROVENANCE ONLY — never rendered. The name of the tool this result
   * answers, carried so the CORE sink can ride it onto AGENT_TOOL_RESULT. The
   * server's tool_executed / $ai_span / tools_used previously resolved 'unknown'
   * whenever it could not pair the result back to its tool_use (an empty callId
   * on the OpenAI arm defeats id pairing), and the wire carried no name to fall
   * back on. The matching `tool_use` block remains the only render source.
   */
  toolName?: string;
  /**
   * Set to `'paused'` ONLY when this live-streamed result is a HITL suspension
   * (the round-engine folded `pausedHalt`). The CORE sink reads it to ride
   * `paused:true` onto AGENT_TOOL_RESULT so the relay/web treat the pause as a
   * typed outcome, never an error. Absent for every ordinary tool result — the
   * literal type makes any other status a compile error, matching the one use.
   */
  status?: 'paused';
  /**
   * Server-enriched result display for Composio/integration tools (the formatted
   * card). Carried on the live-streamed tool_result block so the CORE sink can
   * forward it onto AGENT_TOOL_RESULT (parity with the legacy Claude processor's
   * resultDisplay enrichment + the tool_use block's `display`). Optional — absent
   * for plain tools and arms that don't enrich (native/openai today).
   */
  resultDisplay?: ToolResultDisplay;
  /**
   * S2a computer-use — the browser actuator's ground-truth action report, lifted
   * off the ToolResult envelope (`report` sibling of `content`) by the tool
   * dispatcher and carried on the live-streamed tool_result block (mirrors how
   * `resultDisplay` rides). Intended shape: `BrowserActionReport`
   * (packages/shared/src/computer-use/action-report.ts) — typed `unknown` here
   * because @vestra/agent-sdk deliberately does NOT depend on @bash/shared; the
   * dispatcher applies a minimal structural check and the full
   * `isBrowserActionReport` guard runs at the sandbox boundary (apps/sandbox
   * imports both packages). Absent for every non-browser tool → byte-identical.
   */
  report?: unknown;
}

