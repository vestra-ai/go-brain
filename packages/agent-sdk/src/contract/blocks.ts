/**
 * Media attachment on a USER turn (video / audio / PDF) — spec
 * docs/superpowers/specs/2026-09-04-video-understanding-design.md §4.
 * Never bytes, never a Google file uri: the path the message pointer names,
 * the signed download url from the sync ref (absent for a PDF the server
 * wrote straight to disk), and the content hash once known. Only the Gemini
 * Interactions projection reads this block; every other dialect ignores it.
 */
export interface MediaBlock {
  type: 'media';
  kind: 'video' | 'audio' | 'document';
  filename: string;
  /** Volume-relative path — the `files/<name>` the message pointer shows. */
  path: string;
  /** Signed download url from the `.ref.yaml`; absent when the bytes were written directly. */
  url?: string;
  mediaType: string;
  /** Size of the file. 0 = UNKNOWN, never "empty": the sync ref may omit it and
   *  the bytes may not have landed in the volume yet. A consumer that needs a
   *  true size (a Files-API upload, a limit check) must stat the real file. */
  sizeBytes: number;
  /** sha256 hex of the bytes, once computed. */
  contentSha?: string;
}

